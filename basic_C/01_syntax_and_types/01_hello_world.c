// #include is a preprocessor directive.
// stdio.h stands for "Standard Input Output", which gives us access to printf().
#include <stdio.h>

// main() is the entry point of every C program.
// "int" means the function will return an integer value back to the operating system.
// "void" inside the parentheses means main takes no input arguments.
int main(void) {

    // printf() displays formatted text on the screen.
    // '\n' is an escape sequence for a new line.
    printf("Hello, World! Welcome to C Programming.\n");

    // Returning 0 indicates to the operating system that the program ran successfully.
    return 0;
}
